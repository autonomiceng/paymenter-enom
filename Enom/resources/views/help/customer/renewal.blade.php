<h2>Expiry date and invoice due date</h2>
<p>The expiry date is when the registration ends at the registrar. A renewal invoice is due earlier, so the renewal can be sent before the domain expires.</p>
<h2>How renewal works</h2>
<p>The domain page says when the next renewal invoice is sent and when it is due. The domain renews after the invoice is paid in full and the registrar confirms the new expiry date. Until then, the old expiry date stays on the page.</p>
<p>If the domain page says The operator handles renewal for this domain, you will not get new renewal invoices for it. Renewal invoices issued before then stay listed on the domain page with their own status.</p>
<p>If the operator has turned on credit payment for your domain, a renewal invoice is paid from your account credit only when the credit covers the whole invoice.</p>
<h2>While a registration or transfer is pending</h2>
<p>Renewal settings apply after the registrar confirms the registration or transfer. Until then the domain has no confirmed expiry date, and no renewal is scheduled.</p>
<ul class="enom-list space-y-1">
    <li>If you turn renewal off before the registration or transfer is sent to the registrar, it will not be sent, even after its invoice is paid.</li>
    <li>If it was already sent, it can still complete.</li>
    <li>Turning renewal off does not cancel or refund the registration or transfer invoice.</li>
    <li>Renewal cannot be turned back on from the domain page until the domain is active with a future expiry date. Contact support if you change your mind.</li>
</ul>
<h2>Turning renewal off</h2>
<ul class="enom-list space-y-1">
    <li>The service is set to end at the end of its current period.</li>
    <li>Eligible unpaid renewal invoices are cancelled right away. Contact support to review any remaining renewal invoice.</li>
    <li>Do not pay a renewal invoice while renewal is off. It will not be sent to the registrar.</li>
    <li>If The operator handles renewal for the domain, The operator stops renewing it. A renewal already sent to the registrar can still complete.</li>
</ul>
<h2>Turning renewal back on</h2>
<p>This needs an active domain with a future expiry date and no request still being checked. Cancelled invoices stay cancelled. If the payment due date has already passed, contact support for a new invoice.</p>
