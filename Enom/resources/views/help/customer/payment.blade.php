<h2>How to pay</h2>
<p>Open the invoice and choose Pay. A domain request starts only after its invoice is paid in full.</p>
<h2>If a card is declined</h2>
<p>You can try again in the same payment window. If you close the window and choose Pay again, a new payment session starts.</p>
<h2>Payment processing</h2>
<p>While the invoice says Payment processing, wait for it to finish instead of paying again.</p>
<h2>After payment</h2>
<p>A paid invoice does not mean the registrar has finished. The domain page shows the request status, and the expiry date changes only after the registrar confirms it. See Request statuses for what each status means.</p>
