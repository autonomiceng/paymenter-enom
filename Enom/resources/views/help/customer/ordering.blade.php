<h2>What you can order</h2>
<p>You can register a new .com domain or transfer a .com domain from another registrar, one year at a time. Premium domains and other endings are not available.</p>
<h2>Quotes</h2>
<p>When you check availability, you get a quote. It expires 15 minutes later, so continue to the invoice before then. Availability can change before you pay. If the domain is taken in the meantime, the registrar declines the request and the domain page shows it as declined. Contact support about your payment if that happens.</p>
<h2>Contacts</h2>
<p>The contact you enter on the order page is used for all four domain contacts: registrant, administrative, technical and billing. You can review each one on the domain page later.</p>
<h2>The invoice</h2>
<p>Continuing creates an invoice that is due in 7 days. We do not email it. You go straight to it, and it is also in your invoice list. Paying it in full starts the registrar request.</p>
<h2>Transfers</h2>
<ol class="enom-steps space-y-1">
    <li>At your current registrar, turn off the registrar lock.</li>
    <li>Get the transfer code, also called the auth code, from your current registrar.</li>
    <li>Choose Transfer from another registrar on the Domains page and check availability.</li>
    <li>Enter the contact details and the transfer code, then continue to the invoice and pay it.</li>
</ol>
<p>The transfer code is stored encrypted and only until the transfer request finishes. If the order form shows an error, we clear the code field, so enter it again before you continue.</p>
<p>After payment, the domain page shows Transfer in progress until the registrar confirms the transfer. This can take several days.</p>
