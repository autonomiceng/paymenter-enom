<h2>Sync transfer code</h2>
<p>This asks the registrar to sync the domain's transfer code with the registry. The code is not shown here and is not emailed. When the registrar accepts the sync, the request shows Accepted by the registrar.</p>
<h2>Viewing the code</h2>
<p>Viewing or emailing your transfer code is not available in this portal. Contact support if you plan to move this domain to another registrar.</p>
