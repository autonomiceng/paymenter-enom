<h2>Buying and renewing</h2>
<p>Contact privacy is bought one year at a time. Buying or renewing creates an invoice, and privacy is requested from the registrar after it is paid in full. Privacy does not renew by itself.</p>
<h2>Turning privacy on or off</h2>
<p>You can turn privacy off and on again while your subscription is active. Turning it off keeps your paid subscription.</p>
<h2>When it is not available</h2>
<p>Privacy depends on the registrar allowing it for the domain and on a privacy price being set. If the domain page says privacy is not available, refresh the status or contact support.</p>
